import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const cli = join(repoRoot, "instagram-archive-cli", "src", "cli.ts");

let root: string | null = null;

function useTempRoot(): string {
  root = mkdtempSync(join(tmpdir(), "ig-cli-process-"));
  return root;
}

function run(args: readonly string[]) {
  return spawnSync(process.execPath, [cli, ...args], { encoding: "utf8", timeout: 30_000 });
}

afterEach(() => {
  if (root) {
    rmSync(root, { recursive: true, force: true });
    root = null;
  }
});

describe("instagram archive CLI process boundary", () => {
  it("returns help, version and usage failures as distinct exit statuses", () => {
    const help = run(["--help"]);
    expect(help.status).toBe(0);
    expect(help.stdout).toContain("instagram-archive <command>");

    const version = run(["--version"]);
    expect(version.status).toBe(0);
    expect(version.stdout).toBe("instagram-archive 0.1.0\n");

    for (const args of [["nope"], ["scan", "@alice", "--pause-ms=-1"], ["get", "@alice", "--limit=0"]]) {
      const bad = run(args);
      expect(bad.status).toBe(2);
      expect(bad.stderr.length).toBeGreaterThan(0);
    }
  });

  it("builds and inspects an archive without opening a browser", () => {
    const out = useTempRoot();
    const built = run(["build", "--out", out]);
    expect(built.status).toBe(0);
    expect(built.stdout).toBe(`Built 0 collections and 0 posts at ${out}/index.html\n`);
    expect(readFileSync(join(out, "index.html"), "utf8")).toContain("<title>Instagram archive</title>");
    expect(readFileSync(join(out, "README.md"), "utf8")).toContain("Generated by `pnpm tools ig`");

    const info = run(["info", "--out", out]);
    expect(info.status).toBe(0);
    expect(info.stdout).toBe("0 collection(s), 0 post(s)\n");
  });

  it("refuses work on a parked job until --resume is passed", () => {
    const out = useTempRoot();
    mkdirSync(out, { recursive: true });
    writeFileSync(join(out, "job.json"), JSON.stringify({
      reason: "rate_limit", message: "429", operation: "profile.posts",
      collection: "alice", lastCompleted: "abc", parkedAt: "2026-11-25T00:00:00Z",
    }));

    const blocked = run(["build", "--out", out]);
    expect(blocked.status).toBe(1);
    expect(blocked.stderr).toContain("No work was started. Pass --resume after resolving it deliberately.");
    expect(blocked.stdout).toBe("");

    const resumed = run(["build", "--out", out, "--resume"]);
    expect(resumed.status).toBe(0);
    expect(resumed.stdout).toContain("Built 0 collections");
  });
});
